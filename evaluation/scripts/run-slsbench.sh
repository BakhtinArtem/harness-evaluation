#!/usr/bin/env bash
# Run slsbench harness for a single (app, scenario, phase, run) combination.
# Expects probe-bodies to have been run already (via run-probe-all.sh).
#
# Usage: ./run-slsbench.sh <app> <scenario> <phase> <run_number>
#   app:        spring | quarkus | quarkus-jvm
#   scenario:   read-heavy | mixed | lifecycle
#   phase:      cold | steady
#   run_number: integer repetition index
#
# Requires slsbench DooD image built from the serverless-benchmarking repo.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
EVAL_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
source "$EVAL_DIR/config.env"

APP="${1:?Usage: $0 <app> <scenario> <phase> <run_number>}"
SCENARIO="${2:?}"
PHASE="${3:?}"
RUN="${4:?}"

case "$APP" in
    spring)
        COMPOSE_FILE="$EVAL_DIR/$SPRING_COMPOSE"
        SERVICE_NAME="$SPRING_SERVICE_NAME"
        PORT="$SPRING_PORT"
        OPENAPI_PATH="$EVAL_DIR/$SPRING_OPENAPI"
        ;;
    quarkus)
        COMPOSE_FILE="$EVAL_DIR/$QUARKUS_COMPOSE"
        SERVICE_NAME="$QUARKUS_SERVICE_NAME"
        PORT="$QUARKUS_PORT"
        OPENAPI_PATH="$EVAL_DIR/$QUARKUS_OPENAPI"
        ;;
    quarkus-jvm)
        COMPOSE_FILE="$EVAL_DIR/$QUARKUS_JVM_COMPOSE"
        SERVICE_NAME="$QUARKUS_JVM_SERVICE_NAME"
        PORT="$QUARKUS_JVM_PORT"
        OPENAPI_PATH="$EVAL_DIR/$QUARKUS_JVM_OPENAPI"
        ;;
    *)
        echo "Unknown app: $APP" >&2
        exit 1
        ;;
esac

# quarkus-jvm reuses the quarkus flow files and probe-bodies cache
FLOW_APP="$APP"
if [ "$APP" = "quarkus-jvm" ]; then
    FLOW_APP="quarkus"
fi
FLOW_FILE="$EVAL_DIR/flows/$FLOW_APP/$SCENARIO.yaml"
if [ ! -f "$FLOW_FILE" ]; then
    echo "Flow file not found: $FLOW_FILE" >&2
    exit 1
fi

# ---------------------------------------------------------------------------
# Discover cached probe-bodies result (generated by run-probe-all.sh).
# Cache lives at results/<flow_app>/slsbench/<scenario>/probe-bodies/
# ---------------------------------------------------------------------------

PROBE_CACHE="$EVAL_DIR/results/$FLOW_APP/slsbench/$SCENARIO/probe-bodies"
PROBE_RESULT=$(find "$PROBE_CACHE" -maxdepth 1 -type d -name 'probe-bodies-result-*' 2>/dev/null | sort | tail -1)

if [ -z "$PROBE_RESULT" ]; then
    echo "ERROR: No cached probe-bodies result found at $PROBE_CACHE" >&2
    echo "  Run ./scripts/run-probe-all.sh first." >&2
    exit 1
fi

echo "Using cached probe-bodies: $PROBE_RESULT"

# ---------------------------------------------------------------------------
# Run harness for each rate, reusing the shared probe-bodies result.
# slsbench manages Docker Compose lifecycle, wrk2-flow containers,
# container stats, and first-response measurement internally.
# ---------------------------------------------------------------------------

if [ "$PHASE" = "cold" ]; then
    DURATION="$DURATION_COLD"
else
    DURATION="$DURATION_STEADY"
fi

for RATE in $RATES; do
    RESULT_DIR="$EVAL_DIR/results/$APP/slsbench/$SCENARIO/$PHASE/R${RATE}/run-${RUN}"
    mkdir -p "$RESULT_DIR"

    echo "=== harness | app=$APP scenario=$SCENARIO phase=$PHASE rate=$RATE run=$RUN ==="

    TEMP_FLOW="$RESULT_DIR/flow.yaml"
    sed "s|-t2 -c5 -d[^ ]* -R[0-9]*|-t${WRK2_THREADS} -c${WRK2_CONNECTIONS} -d${DURATION} -R${RATE}|" \
        "$FLOW_FILE" > "$TEMP_FLOW"

    if [ "$PHASE" = "steady" ]; then
        echo "  Injecting warmup stage (${WARMUP_DURATION} at R=${WARMUP_RATE})..."
        python3 -c "
import yaml, sys, copy
with open(sys.argv[1]) as f:
    doc = yaml.safe_load(f)
sname = list(doc['stages'].keys())[0]
warmup = copy.deepcopy(doc['stages'][sname])
warmup['wrk2params'] = sys.argv[2]
doc['stages'] = {'00-warmup': warmup, **doc['stages']}
with open(sys.argv[1], 'w') as f:
    yaml.dump(doc, f, default_flow_style=False, sort_keys=False)
" "$TEMP_FLOW" "-t1 -c2 -d${WARMUP_DURATION} -R${WARMUP_RATE}"
    fi

    echo "  Running harness..."
    docker run --rm \
        --network=host \
        -v "$DOCKER_SOCKET:$DOCKER_SOCKET" \
        -v "$TEMP_FLOW:/workspace/flow.yaml:ro" \
        -v "$OPENAPI_PATH:/workspace/openapi.yaml:ro" \
        -v "$COMPOSE_FILE:/workspace/docker-compose.yml:ro" \
        -v "$PROBE_RESULT:/workspace/probe-result:ro" \
        -v "$RESULT_DIR:/workspace/results" \
        "$SLSBENCH_IMAGE" harness \
            --flow-path /workspace/flow.yaml \
            --probe-bodies-path /workspace/probe-result \
            --openapi-spec-path /workspace/openapi.yaml \
            --docker-compose-path /workspace/docker-compose.yml \
            --docker-socket-path "$DOCKER_SOCKET" \
            --service-name "$SERVICE_NAME" \
            --port "$PORT" \
            --result-path /workspace/results \
            --debug-non2xx \
        2>&1 | tee "$RESULT_DIR/harness.log"

    echo "  Results saved to $RESULT_DIR"
done

echo "=== slsbench complete for $APP/$SCENARIO/$PHASE/run-$RUN ==="
